const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('launcherAPI', {
  listApps: () => ipcRenderer.invoke('apps:list'),
  addApp: (formData) => ipcRenderer.invoke('apps:add', formData),
  updateApp: (id, formData) => ipcRenderer.invoke('apps:update', { id, formData }),
  removeApp: (id) => ipcRenderer.invoke('apps:remove', id),
  launchApp: (id) => ipcRenderer.invoke('apps:launch', id),
  pickTarget: (kind) => ipcRenderer.invoke('dialog:pickTarget', kind),
  pickIcon: () => ipcRenderer.invoke('dialog:pickIcon'),
  extractIconPreview: (targetPath) => ipcRenderer.invoke('icon:extractPreview', targetPath),
  fetchFaviconPreview: (url) => ipcRenderer.invoke('icon:fetchFaviconPreview', url),
  detectMissingIcons: () => ipcRenderer.invoke('apps:detectMissingIcons'),
  restoreDefaults: () => ipcRenderer.invoke('apps:restoreDefaults'),
  emptyRecycleBin: () => ipcRenderer.invoke('system:emptyRecycleBin'),
  getVolume: () => ipcRenderer.invoke('system:getVolume'),
  setVolume: (pct) => ipcRenderer.invoke('system:setVolume', pct),
  setMuted: (muted) => ipcRenderer.invoke('system:setMuted', muted),
  openNetworkSettings: () => ipcRenderer.invoke('system:openNetworkSettings'),
  listAudioDevices: () => ipcRenderer.invoke('system:listAudioDevices'),
  setAudioDevice: (deviceId) => ipcRenderer.invoke('system:setAudioDevice', deviceId),
  listAudioSessions: () => ipcRenderer.invoke('system:listAudioSessions'),
  setSessionVolume: (pid, pct) => ipcRenderer.invoke('system:setSessionVolume', pid, pct),
  setSessionMuted: (pid, muted) => ipcRenderer.invoke('system:setSessionMuted', pid, muted),
  listUsbDrives: () => ipcRenderer.invoke('system:listUsbDrives'),
  ejectDrive: (driveLetter) => ipcRenderer.invoke('system:ejectDrive', driveLetter),
  listOpenWindows: () => ipcRenderer.invoke('system:listOpenWindows'),
  focusWindow: (handle) => ipcRenderer.invoke('system:focusWindow', handle),
  listBluetoothDevices: () => ipcRenderer.invoke('system:listBluetoothDevices'),
  disconnectBluetoothDevice: (instanceId) => ipcRenderer.invoke('system:disconnectBluetoothDevice', instanceId),
  shutdown: () => ipcRenderer.invoke('system:shutdown'),
  restart: () => ipcRenderer.invoke('system:restart'),
  sleep: () => ipcRenderer.invoke('system:sleep'),
  listWifiNetworks: () => ipcRenderer.invoke('system:listWifiNetworks'),
  connectWifi: (ssid) => ipcRenderer.invoke('system:connectWifi', ssid),
  disconnectWifi: () => ipcRenderer.invoke('system:disconnectWifi'),
  getMinimizeToTrayOnClose: () => ipcRenderer.invoke('settings:getMinimizeToTrayOnClose'),
  setMinimizeToTrayOnClose: (enable) => ipcRenderer.invoke('settings:setMinimizeToTrayOnClose', enable),
  isFullscreen: () => ipcRenderer.invoke('window:isFullscreen'),
  toggleFullscreen: () => ipcRenderer.invoke('window:toggleFullscreen'),
  onFullscreenChanged: (callback) => ipcRenderer.on('fullscreen-changed', (_e, isFullscreen) => callback(isFullscreen)),
  addIsland: (name, parentId, color) => ipcRenderer.invoke('folder:add', { name, parentId, color }),
  renameItem: (id, name) => ipcRenderer.invoke('item:rename', { id, name }),
  setColor: (id, color) => ipcRenderer.invoke('item:setColor', { id, color }),
  moveItem: (id, parentId) => ipcRenderer.invoke('item:move', { id, parentId }),
  togglePin: (id) => ipcRenderer.invoke('item:togglePin', id),
  setPinned: (id, pinned) => ipcRenderer.invoke('item:setPinned', { id, pinned }),
  setPinOrder: (orderedIds) => ipcRenderer.invoke('item:setPinOrder', orderedIds),
  setPositions: (updates) => ipcRenderer.invoke('item:setPositions', updates),
  setPosition: (id, gridX, gridY) => ipcRenderer.invoke('item:setPosition', { id, gridX, gridY }),
  setCollapsed: (id, collapsed) => ipcRenderer.invoke('item:setCollapsed', { id, collapsed }),
  setShowNames: (id, showNames) => ipcRenderer.invoke('item:setShowNames', { id, showNames }),
  setSize: (id, w, h) => ipcRenderer.invoke('item:setSize', { id, w, h }),
  getAutoLaunch: () => ipcRenderer.invoke('settings:getAutoLaunch'),
  setAutoLaunch: (enable) => ipcRenderer.invoke('settings:setAutoLaunch', enable),
  getStartFullscreen: () => ipcRenderer.invoke('settings:getStartFullscreen'),
  setStartFullscreen: (enable) => ipcRenderer.invoke('settings:setStartFullscreen', enable),
  getHotkey: () => ipcRenderer.invoke('settings:getHotkey'),
  setHotkey: (accelerator) => ipcRenderer.invoke('settings:setHotkey', accelerator),
  getVersion: () => ipcRenderer.invoke('app:getVersion'),
  exportBackup: () => ipcRenderer.invoke('backup:export'),
  importBackup: () => ipcRenderer.invoke('backup:import'),
  getPathForFile: (file) => webUtils.getPathForFile(file),
});
